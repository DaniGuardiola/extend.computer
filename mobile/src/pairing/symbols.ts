export function validSymbols(symbols: unknown): symbols is number[] {
  return (
    Array.isArray(symbols) &&
    symbols.length === 8 &&
    symbols.every(
      (index) =>
        Number.isInteger(index) &&
        index >= 0 &&
        index < verificationAlphabet.length,
    )
  );
}
