package computer.extend.android

/** Standalone JVM checks; no emulator, Android UI or duplicated JNI fake. */
fun main() {
  val trace = mutableListOf<TouchCommand>()
  val full = TouchGeometry(100.0, 50.0, 1000.0, 500.0, 0.0, 0.0, 1.0, 1.0, 2000.0, 1000.0)
  val point = TouchPoint(300.0, 200.0)
  val gestures = DisplayTouch(10.0, 30.0, 500, 300, trace::add)
  gestures.geometry = full
  check(!gestures.down(7, TouchPoint(50.0, 200.0), 0))
  check(trace.isEmpty())
  gestures.down(7, point, 0); gestures.up(7, point, 100)
  check(trace.filterIsInstance<TouchCommand.Button>().map { it.down to it.clicks } == listOf(true to 1, false to 1))
  trace.clear(); gestures.down(31, point, 180); gestures.up(31, point, 230)
  check(trace.filterIsInstance<TouchCommand.Button>().map { it.clicks } == listOf(2, 2))
  trace.clear(); gestures.down(4, point, 1000); gestures.hold(1499)
  check(trace.none { it is TouchCommand.Button })
  gestures.hold(1500); gestures.move(mapOf(4 to TouchPoint(350.0, 240.0))); gestures.up(4, TouchPoint(350.0, 240.0), 1700)
  check(trace.filterIsInstance<TouchCommand.Button>().map { it.down } == listOf(true, false))
  trace.clear(); gestures.down(8, point, 2000); gestures.hold(2500)
  gestures.additional(22, linkedMapOf(22 to TouchPoint(400.0, 200.0), 8 to point), 2510)
  check(trace.filterIsInstance<TouchCommand.Button>().map { it.down } == listOf(true, false))
  // Pointer array order changes; stable IDs must preserve centroid and target.
  gestures.move(linkedMapOf(8 to TouchPoint(320.0, 240.0), 22 to TouchPoint(420.0, 240.0)))
  check(trace.filterIsInstance<TouchCommand.Scroll>().single().let { it.dx == 40 && it.dy == 80 && it.point == full.map(point) })
  gestures.up(22, TouchPoint(420.0, 240.0), 2600)
  gestures.move(mapOf(8 to point)); gestures.up(8, point, 2610); gestures.finish()
  check(trace.filterIsInstance<TouchCommand.Button>().size == 2) // No tap after scroll.
  trace.clear(); gestures.down(1, point, 3000)
  gestures.additional(44, mapOf(44 to TouchPoint(400.0, 200.0), 1 to point), 3010)
  gestures.up(1, point, 3070); gestures.up(44, TouchPoint(400.0, 200.0), 3080); gestures.finish()
  check(trace.filterIsInstance<TouchCommand.Button>().map { it.button to it.down } == listOf(1 to true, 1 to false))
  trace.clear(); gestures.down(9, point, 4000); gestures.hold(4500)
  gestures.move(mapOf(9 to TouchPoint(20.0, 200.0))); gestures.up(9, point, 4600)
  check(trace.last() == TouchCommand.Release)
  check(trace.filterIsInstance<TouchCommand.Button>().size == 1)
  trace.clear(); gestures.down(9, point, 5000); gestures.cancel(); gestures.hold(5600); gestures.up(9, point, 5700)
  check(trace.filterIsInstance<TouchCommand.Button>().isEmpty())
  check(trace.last() == TouchCommand.Release)
  val inner = full.copy(contentX = .2, contentY = .1, contentWidth = .6, contentHeight = .8)
  gestures.geometry = inner; trace.clear()
  check(!gestures.down(2, TouchPoint(150.0, 200.0), 6000))
  check(inner.map(point) == TouchPoint(.2, .3))
  check(inner.scroll(TouchPoint(3.0, 2.0)) == TouchPoint(10.0, 5.0))
  gestures.down(2, point, 6100); gestures.hold(6600); gestures.geometry = inner.copy(width = 1200.0)
  check(trace.last() == TouchCommand.Release)
  check(full.map(TouchPoint(Double.NaN, 200.0)) == null)
  println("DisplayTouch: tap, double-tap, drag, pointer-ID scroll, right-tap, bars, cancel and geometry release passed")
}
